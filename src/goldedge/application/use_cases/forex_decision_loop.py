logger = logging.getLogger("forex_decision_loop")


class ForexDecisionLoopUseCase:
    """
    Forex Institutional Decision Engine Orchestrator.
    Executes the comprehensive quantitative decision cycle:
    1. Primary Strategy candidate generation
    2. 2D Kalman Velocity Z-score > 0.5 in signal direction
    3. LightGBM Calibrated Meta-Model Probability > 0.62
    4. Live Spread < 1.8 pips
    5. Hand off executed position to ForexKalmanEntropyExitAgent
    """

    def __init__(
        self,
        broker: IBrokerAdapter,
        market_data: IMarketDataProvider,
        candle_repo: ICandleRepository,
        meta_labeler: IMetaLabeler,
        execute_trade_uc: ExecuteTradeUseCase,
        manage_position_uc: ManagePositionUseCase,
        decision_rules: Optional[ForexDecisionRules] = None,
        micro_model: Optional[IMicrostructureModel] = None,
        micro_gatekeeper: Optional[ForexMicroGatekeeper] = None,
    ):
        self.broker = broker
        self.market_data = market_data
        self.candle_repo = candle_repo
        self.meta_labeler = meta_labeler
        self.execute_trade_uc = execute_trade_uc
        self.manage_position_uc = manage_position_uc
        self.decision_rules = decision_rules or ForexDecisionRules(
            min_kalman_vel_z=0.5,
            min_meta_prob=0.62,
            max_spread_pips=1.8
        )
        self.micro_model = micro_model
        self.micro_gatekeeper = micro_gatekeeper
        self.regime_detector = RegimeDetectorService()
        self.kalman_filters: Dict[str, StreamingForexKalmanFilter] = {}

    def get_or_create_kalman(self, symbol: str) -> StreamingForexKalmanFilter:
        if symbol not in self.kalman_filters:
            self.kalman_filters[symbol] = StreamingForexKalmanFilter()
        return self.kalman_filters[symbol]

    def evaluate_and_execute(
        self,
        symbol: str,
        account_balance: float = 10000.0,
        current_daily_loss_pct: float = 0.0,
        current_streak: int = 0
    ) -> Optional[int]:
        """
        Executes one full cycle of the quantitative Forex decision loop.
        Returns ticket ID if executed, None otherwise.
        """
        # 1. Fetch live tick
        tick = self.market_data.get_current_tick(symbol)
        if not tick or tick.bid <= 0 or tick.ask <= 0:
            logger.debug(f"[{symbol}] No valid live tick available.")
            return None

        # 2. Compute live spread in pips
        spread_pips = PipCalculator.calculate_spread_pips(tick.bid, tick.ask, symbol)

        # 3. Update Streaming 2D Kalman Filter
        kf = self.get_or_create_kalman(symbol)
        mid_price = tick.last or ((tick.bid + tick.ask) / 2.0)
        vol = float(tick.volume or 1.0)
        k_price, k_vel, k_vel_z = kf.update(mid_price, volume=vol, spread=spread_pips)

        # 4. Generate Primary Strategy Candidate Signals
        bars = self.candle_repo.get_latest_bars(symbol, count=60)
        if len(bars) < 30:
            logger.debug(f"[{symbol}] Insufficient bars for strategy indicators ({len(bars)}/30).")
            return None

        df = IndicatorService.compute_indicators(bars)
        if df.empty:
            return None

        regime = self.regime_detector.detect(df)
        candidate_signals = SignalGeneratorService.generate_signals(df, symbol, regime)
        if not candidate_signals:
            logger.debug(f"[{symbol}] No candidate signal generated by primary strategy.")
            return None

        # Select candidate signal
        candidate: Signal = candidate_signals[0]

        # 5. Build Cyclical Time Features and Microstructure Features for Meta-Model
        now = tick.time if tick.time.tzinfo else tick.time.replace(tzinfo=timezone.utc)
        hour = now.hour + now.minute / 60.0 + now.second / 3600.0
        sin_time = math.sin(2.0 * math.pi * hour / 24.0)
        cos_time = math.cos(2.0 * math.pi * hour / 24.0)

        latest_atr = float(df["atr"].iloc[-1]) if "atr" in df.columns else (mid_price * 0.0005)
        latest_rsi = float(df["rsi"].iloc[-1]) if "rsi" in df.columns else 50.0

        close_series = df["close"] if "close" in df.columns else pd.Series(dtype=float)
        shannon_ent = (
            DenoiseService.compute_rolling_entropy(close_series.pct_change().dropna())
            if len(close_series) > 30 else 2.5
        )
        kaufman_er = (
            DenoiseService.compute_kaufman_er(close_series)
            if len(close_series) > 15 else 0.45
        )
        kalman_accel = kf.get_acceleration() if hasattr(kf, "get_acceleration") else 0.0

        features = {
            "kalman_vel": k_vel,
            "kalman_vel_z": k_vel_z,
            "kalman_accel": kalman_accel,
            "shannon_entropy": shannon_ent,
            "kaufman_er": kaufman_er,
            "rsi_14": latest_rsi,
            "atr_14": latest_atr,
            "spread_pips": spread_pips,
            "tick_momentum": 1.0 if candidate.direction in (SignalDirection.BUY, "BUY") else -1.0,
            "burst_ratio": 1.2,
            "sin_time": sin_time,
            "cos_time": cos_time,
        }

        # 6. Predict Calibrated Win Probability
        meta_prob = self.meta_labeler.predict_probability(features)

        # 7. Evaluate Institutional Decision Rules (Kalman Velocity, Acceleration, Entropy, Meta-prob, Spread)
        decision: ForexDecisionResult = self.decision_rules.evaluate(
            signal=candidate,
            kalman_vel_z=k_vel_z,
            meta_probability=meta_prob,
            spread_pips=spread_pips,
            kalman_accel=kalman_accel,
            entropy=shannon_ent
        )

        if not decision.approved:
            logger.info(
                f"[{symbol}] Trade Rejected by Decision Rules: {', '.join(decision.rejection_reasons)}"
            )
            return None

        # 7.5 Microstructure Hard Gatekeeper Kill-Switch
        if self.micro_gatekeeper is not None:
            micro_prob = self.micro_model.predict_probability(features) if self.micro_model else 0.70
            ofi_30s = float(features.get("OFI_30s", features.get("tick_momentum", 0.0) * 0.2))
            passed, reason = self.micro_gatekeeper.evaluate(
                micro_prob=micro_prob,
                ofi_30s=ofi_30s,
                direction=candidate.direction
            )
            if not passed:
                logger.info(f"[{symbol}] Trade Rejected by Microstructure Kill-Switch: {reason}")
                return None

        logger.info(
            f"[{symbol}] Signal APPROVED: {candidate.strategy} | {candidate.direction.value} | "
            f"Kalman Z: {k_vel_z:.3f} | Meta Win Prob: {meta_prob:.3f} | Spread: {spread_pips:.2f} pips"
        )

        # 8. Sizing and Execution
        scored_sig = ScoredSignal(
            signal=candidate,
            score=meta_prob,
            ml_probability=meta_prob
        )

        self.execute_trade_uc.execute(
            scored_signal=scored_sig,
            current_spread=spread_pips * PipCalculator.get_pip_unit(symbol),
            recent_median_spread=spread_pips * PipCalculator.get_pip_unit(symbol),
            account_balance=account_balance,
            current_daily_loss_pct=current_daily_loss_pct,
            current_streak=current_streak,
            entry_price=mid_price,
            atr_value=latest_atr
        )

        # 9. Hand off to ForexKalmanEntropyExitAgent
        # Locate the opened position in trade_repo
        open_positions = self.manage_position_uc.trade_repo.get_positions_by_status("OPEN")
        matching = [p for p in open_positions if p.symbol == symbol]
        if matching:
            newest_pos = max(matching, key=lambda p: p.time_setup)
            agent = self.manage_position_uc.get_or_create_exit_agent(newest_pos)
            agent.reset(newest_pos.price_open)
            logger.info(f"[{symbol}] Position ticket {newest_pos.ticket} handed off to ForexKalmanEntropyExitAgent.")
            return newest_pos.ticket

        return None
